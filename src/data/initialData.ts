export function generateInitialPlantRecords(): StationEvaluationRecord[] {
  const records: StationEvaluationRecord[] = [];
  let recordIdCounter = 1000;

  INITIAL_PLANTS.forEach((plantName) => {
    const masterInfo = INITIAL_PLANT_MASTERS.find((p) => p.nombre === plantName);
    const ciudadStr = masterInfo ? `${masterInfo.estado} - ${masterInfo.ciudad}` : 'Sinaloa - Topolobampo';

    RUBRO_ITEMS.forEach((item, itemIdx) => {
      const cleanPunto = item.description.trim();
      let calif: number | string = item.maxPoints > 0 ? (item.maxPoints >= 3 ? item.maxPoints - (itemIdx % 2 === 0 ? 0 : 0.5) : item.maxPoints) : 'N/A';
      if (item.isInformative) {
        calif = item.id === 'INF-5.1' ? 8 : item.id === 'INF-5.2' ? 0 : item.id === 'INF-5.3' ? '0%' : item.id === 'INF-5.4' ? '-' : 'N/A';
      }

      records.push({
        id: `plt-rec-${recordIdCounter++}`,
        concatenar: `${plantName}SEPTIEMBRE${cleanPunto}`,
        ciudad: ciudadStr,
        estacion: plantName,
        mes: 'SEPTIEMBRE',
        anio: 2026,
        punto: cleanPunto,
        calificacion: calif,
        rubroId: item.rubroId,
        observaciones: itemIdx === 0 ? 'Inspección de sistemas de planta verificada conforme a normativa industrial vigente.' : undefined,
      });
    });
  });

  return records;
}

