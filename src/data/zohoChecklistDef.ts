export interface ZohoChecklistItemDef {
  index: number; // 1 to 54
  id: string; // e.g. "1.1", "2.1", "INF-3.1"
  rubroId: number; // 1 to 5
  rubroName: string;
  norma: string;
  punto: string; // Exact text matching CSV "PUNTO A REVISAR"
  maxPoints: number;
  isInformative?: boolean;
  inputType?: 'score' | 'number' | 'text';
  suggestedScores?: (number | string)[];
  defaultScore?: number | string;
  presetFindings?: string[];
}


/**
 * Generates scores stepped by 0.5 from 0 up to maxPoints, plus N/A
 * e.g. max 3 -> [0, 0.5, 1, 1.5, 2, 2.5, 3, "N/A"]
 * e.g. max 5 -> [0, 0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5, "N/A"]
 * e.g. max 2 -> [0, 0.5, 1, 1.5, 2, "N/A"]
 */
export function generateStepScores(maxPoints: number, allowNA = true): (number | string)[] {
  const scores: (number | string)[] = [];
  for (let s = 0; s <= maxPoints + 0.0001; s += 0.5) {
    scores.push(Math.round(s * 10) / 10);
  }
  if (allowNA) {
    scores.push("N/A");
  }
  return scores;
}

